<?php

declare(strict_types=1);

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class CompanyIdentityTradeProfile extends Model
{
    /**
     * --------------------------------------------------------------------------
     * Table
     * --------------------------------------------------------------------------
     */

    protected $table = 'company_identity_trade_profiles';

    /**
     * --------------------------------------------------------------------------
     * Mass Assignment
     * --------------------------------------------------------------------------
     */

    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Relationship
        |--------------------------------------------------------------------------
        */

        'company_identity_id',

        /*
        |--------------------------------------------------------------------------
        | Trade Roles™
        |--------------------------------------------------------------------------
        */

        'trade_roles',

        /*
        |--------------------------------------------------------------------------
        | Export Experience
        |--------------------------------------------------------------------------
        */

        'export_experience',

        'export_since',

        /*
        |--------------------------------------------------------------------------
        | Trade Geography
        |--------------------------------------------------------------------------
        */

        'export_countries',

        'import_countries',

        /*
        |--------------------------------------------------------------------------
        | Supply Chain
        |--------------------------------------------------------------------------
        */

        'main_industries',

        'domestic_markets',

        /*
        |--------------------------------------------------------------------------
        | Future Trade Intelligence™
        |--------------------------------------------------------------------------
        */

        'export_products',

        'import_products',

        'trade_notes',

        /*
        |--------------------------------------------------------------------------
        | Buyer Trust™
        |--------------------------------------------------------------------------
        */

        'trade_profile_score',

        /*
        |--------------------------------------------------------------------------
        | Verification™
        |--------------------------------------------------------------------------
        */

        'verification_status',

        'verified_at',

        'verified_by',

        'last_reviewed_at',

        /*
        |--------------------------------------------------------------------------
        | Audit
        |--------------------------------------------------------------------------
        */

        'created_by',

        'updated_by',
    ];

    /**
     * --------------------------------------------------------------------------
     * Attribute Casting
     * --------------------------------------------------------------------------
     */

    protected $casts = [

        /*
        |--------------------------------------------------------------------------
        | JSON
        |--------------------------------------------------------------------------
        */

        'trade_roles'       => 'array',

        'export_countries'  => 'array',

        'import_countries'  => 'array',

        'main_industries'   => 'array',

        'domestic_markets'  => 'array',

        'export_products'   => 'array',

        'import_products'   => 'array',

        /*
        |--------------------------------------------------------------------------
        | Dates
        |--------------------------------------------------------------------------
        */

        'verified_at'       => 'datetime',

        'last_reviewed_at'  => 'datetime',

        /*
        |--------------------------------------------------------------------------
        | Boolean
        |--------------------------------------------------------------------------
        */

        'trade_profile_score' => 'integer',
    ];

    /**
     * --------------------------------------------------------------------------
     * Canonical Company Identity
     * --------------------------------------------------------------------------
     */

    public function companyIdentity(): BelongsTo
    {
        return $this->belongsTo(
            CompanyIdentity::class
        );
    }

    /**
     * --------------------------------------------------------------------------
     * Verified By
     * --------------------------------------------------------------------------
     */

    public function verifier(): BelongsTo
    {
        return $this->belongsTo(
            User::class,
            'verified_by'
        );
    }

    /**
     * --------------------------------------------------------------------------
     * Created By
     * --------------------------------------------------------------------------
     */

    public function creator(): BelongsTo
    {
        return $this->belongsTo(
            User::class,
            'created_by'
        );
    }

    /**
     * --------------------------------------------------------------------------
     * Updated By
     * --------------------------------------------------------------------------
     */

    public function updater(): BelongsTo
    {
        return $this->belongsTo(
            User::class,
            'updated_by'
        );
    }
}